-- Consulta somente leitura do estado do agendador para a conta autenticada.
-- Evita afirmar que o backup semanal esta ativo apenas por existir uma copia antiga.
CREATE OR REPLACE FUNCTION public.ua_backup_semanal_status()
RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path = ''
AS $status$
DECLARE
 usuario uuid := auth.uid();
 ativo boolean := false;
 qtd integer := 0;
 ultima timestamptz;
BEGIN
 IF usuario IS NULL THEN
  RAISE EXCEPTION 'Autenticacao obrigatoria para consultar backup.' USING ERRCODE='28000';
 END IF;
 IF to_regclass('cron.job') IS NOT NULL THEN
  EXECUTE 'SELECT EXISTS (SELECT 1 FROM cron.job WHERE jobname=''oficina-1-0-backup-semanal'' AND active)'
   INTO ativo;
 END IF;
 SELECT count(*), max(criado_em) INTO qtd, ultima
 FROM public.ua_backups_semanais WHERE user_id=usuario;
 RETURN jsonb_build_object('agendamento_ativo',ativo,'quantidade',qtd,'ultima_copia',ultima,'retencao',4);
END
$status$;
REVOKE ALL ON FUNCTION public.ua_backup_semanal_status() FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.ua_backup_semanal_status() TO authenticated;

COMMENT ON TABLE public.ua_backups_semanais IS
 'Copias semanais internas OFICINA 1.0. Quatro ultimas por conta. Nao substitui copia externa criptografada.';
COMMIT;
NOTIFY pgrst, 'reload schema';

-- AGENDAMENTO DO SUPABASE CRON
-- UNIVERSA ART - OFICINA 1.0 | ATIVAR AGENDAMENTO SEMANAL
-- PREREQUISITO: executar antes backup-semanal-estrutura-oficina-1-0.sql
-- Execute no SQL Editor do projeto oficina-universa-arte, como proprietario.
-- Esta acao NAO apaga pedidos, clientes ou documento principal.
-- Habilita Supabase Cron (pg_cron), quando disponivel no projeto.
CREATE EXTENSION IF NOT EXISTS pg_cron;

BEGIN;
-- Cria copia inicial antes de agendar; se der erro, nao removera backups anteriores.
SELECT public.ua_backup_semanal_gerar() AS copias_iniciais_criadas;
-- Todo domingo as 06:00 UTC = 03:00 no horario de Sao Paulo (UTC-3).
-- Cron substitui o agendamento se o mesmo nome for executado novamente.
SELECT cron.schedule(
 'oficina-1-0-backup-semanal',
 '0 6 * * 0',
 $$ SELECT public.ua_backup_semanal_gerar(); $$
) AS identificador_da_agenda;
COMMIT;

-- Verifique active=true e o nome do job na resposta. A execucao real deve
-- ser acompanhada em Integrations > Cron > Jobs > History no Supabase.
SELECT jobid, jobname, schedule, active
FROM cron.job WHERE jobname='oficina-1-0-backup-semanal';

SELECT semana_utc, criado_em, revisao_origem
FROM public.ua_backups_semanais ORDER BY criado_em DESC LIMIT 4;

