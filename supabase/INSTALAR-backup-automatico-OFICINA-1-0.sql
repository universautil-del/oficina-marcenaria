-- Este snapshot e uma COPIA NO MESMO PROJETO: mantenha tambem backup manual fora do Supabase.
BEGIN;

CREATE TABLE IF NOT EXISTS public.ua_backups_semanais (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
 semana_utc date NOT NULL,
 criado_em timestamptz NOT NULL DEFAULT now(),
 revisao_origem bigint NOT NULL CHECK (revisao_origem >= 1),
 dados jsonb NOT NULL,
 assinatura_md5 text NOT NULL,
 CONSTRAINT ua_backup_uma_copia_por_semana UNIQUE (user_id, semana_utc)
);

CREATE INDEX IF NOT EXISTS ua_backups_semanais_usuario_data
 ON public.ua_backups_semanais(user_id, criado_em DESC);

ALTER TABLE public.ua_backups_semanais ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.ua_backups_semanais FROM PUBLIC, anon, authenticated;
GRANT SELECT ON public.ua_backups_semanais TO authenticated;
-- O usuario le apenas suas copias; insercao/exclusao sao reservadas ao job de banco.
DROP POLICY IF EXISTS ua_backup_ver_somente_seus ON public.ua_backups_semanais;
CREATE POLICY ua_backup_ver_somente_seus ON public.ua_backups_semanais
 FOR SELECT TO authenticated USING ((SELECT auth.uid()) = user_id);

REVOKE ALL ON SEQUENCE public.ua_backups_semanais_id_seq FROM PUBLIC, anon, authenticated;

-- Sem parametros para usuarios: somente o agendador privilegiado executa.
-- Em uma transacao, copia o documento exato (JSONB), verifica leitura de volta
-- e so entao remove versoes que excederem as ultimas 4 copias DO MESMO usuario.
CREATE OR REPLACE FUNCTION public.ua_backup_semanal_gerar()
RETURNS integer
LANGUAGE plpgsql SECURITY DEFINER SET search_path = ''
AS $func$
DECLARE
 item record;
 copia_id bigint;
 copie_iguais boolean;
 total integer := 0;
 semana date := date_trunc('week', timezone('UTC', now()))::date;
BEGIN
 FOR item IN
  SELECT user_id, data, revision
  FROM public.universalartes_preview_backups
 LOOP
  IF item.data IS NULL OR item.data->>'version' <> '3' THEN
   RAISE EXCEPTION 'Backup nao criado para conta %: documento invalido.', item.user_id;
  END IF;
  copia_id := NULL;
  INSERT INTO public.ua_backups_semanais(user_id, semana_utc, revisao_origem, dados, assinatura_md5)
  VALUES (item.user_id, semana, item.revision, item.data, md5(item.data::text))
  ON CONFLICT (user_id, semana_utc) DO NOTHING
  RETURNING id INTO copia_id;
  IF copia_id IS NULL THEN
    CONTINUE; -- Job repetido na mesma semana nao modifica a copia anterior.
  END IF;
  SELECT b.dados = item.data
     AND b.revisao_origem = item.revision
     AND b.assinatura_md5 = md5(item.data::text)
  INTO copie_iguais FROM public.ua_backups_semanais b WHERE b.id=copia_id;
  IF copie_iguais IS DISTINCT FROM TRUE THEN
   RAISE EXCEPTION 'Integridade do backup nao confirmada para conta %.', item.user_id;
  END IF;

  -- Apagar a 5a copia em diante APENAS apos persistir nova copia valida.
  -- Quando falha a nova gravacao, a transacao e revertida e as antigas ficam.
  DELETE FROM public.ua_backups_semanais b
  WHERE b.user_id=item.user_id AND b.id IN (
    SELECT antigo.id FROM (
      SELECT id, row_number() OVER (ORDER BY semana_utc DESC, id DESC) AS pos
      FROM public.ua_backups_semanais
      WHERE user_id=item.user_id
    ) AS antigo WHERE antigo.pos>4
  );
  total := total + 1;
 END LOOP;
 RETURN total;
END
$func$;

REVOKE ALL ON FUNCTION public.ua_backup_semanal_gerar() FROM PUBLIC, anon, authenticated;
-- A funcao pertence ao proprietario da migracao (postgres no SQL Editor).
